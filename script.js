function updatePageProgress() {
  const documentHeight = document.documentElement.scrollHeight - window.innerHeight;
  const progress = documentHeight > 0 ? (window.scrollY / documentHeight) * 100 : 0;
  document.querySelector(".scroll-progress span").style.width = `${Math.min(progress, 100)}%`;
  document.querySelector(".header").classList.toggle("scrolled", window.scrollY > 18);
  updateProcessProgress();
  updateActiveNavigation();
}

function updateProcessProgress() {
  const process = document.querySelector("#process-steps");
  if (!process || !process.children.length) return;

  const section = process.closest(".partnershipMethod");
  const stickyInner = section.querySelector(".partnershipMethodInner");
  const sectionRect = section.getBoundingClientRect();
  const navbarHeight = parseFloat(
    getComputedStyle(document.documentElement).getPropertyValue("--navbar-height")
  ) || 0;
  const usesSticky = getComputedStyle(stickyInner).position === "sticky";
  const start = usesSticky ? navbarHeight : window.innerHeight * 0.82;
  const distance = usesSticky
    ? Math.max(sectionRect.height - stickyInner.offsetHeight, 1)
    : Math.max(sectionRect.height + window.innerHeight * 0.52, 1);
  const progress = Math.min(Math.max((start - sectionRect.top) / distance, 0), 1);
  const steps = Array.from(process.children);
  const currentIndex = Math.min(
    Math.floor(progress * steps.length),
    steps.length - 1
  );

  process.style.setProperty("--process-progress", progress.toFixed(3));
  steps.forEach((step, index) => {
    step.classList.toggle("is-reached", index <= currentIndex);
    step.classList.toggle("is-complete", index < currentIndex);
    step.classList.toggle("is-current", index === currentIndex);
  });
}

