function clearFieldError(field) {
  field.removeAttribute("aria-invalid");
  const errorId = field.getAttribute("aria-describedby")?.split(" ").find(id => id.endsWith("-error"));
  if (errorId) document.getElementById(errorId).textContent = "";
}

function showFieldError(field, message) {
  field.setAttribute("aria-invalid", "true");
  const errorId = field.getAttribute("aria-describedby")?.split(" ").find(id => id.endsWith("-error"));
  if (errorId) document.getElementById(errorId).textContent = message;
}

function clearContactErrors() {
  document.querySelectorAll("#contact-form input, #contact-form textarea").forEach(clearFieldError);
  const status = document.querySelector(".formStatus");
  if (status) status.textContent = "";
}

function validateContactForm(form) {
  const validation = content[currentLanguage].validation || content.en.validation;
  const name = form.elements.name;
  const email = form.elements.email;
  const message = form.elements.message;
  const invalidFields = [];

  clearContactErrors();

  if (!name.value.trim()) {
    showFieldError(name, validation.name);
    invalidFields.push(name);
  }
  if (!email.value.trim() || email.validity.typeMismatch) {
    showFieldError(email, validation.email);
    invalidFields.push(email);
  }
  if (!message.value.trim()) {
    showFieldError(message, validation.message);
    invalidFields.push(message);
  }

  return invalidFields;
}

document.querySelector("#contact-form").addEventListener("submit", event => {
  event.preventDefault();
  const t = content[currentLanguage];
  const form = event.currentTarget;
  const invalidFields = validateContactForm(form);
  if (invalidFields.length) {
    invalidFields[0].focus();
    return;
  }

  const values = new FormData(event.currentTarget);
  const subject = encodeURIComponent(`${t.inquirySubject} — ${values.get("company") || t.newPartner}`);
  const body = encodeURIComponent([
    `${t.form[0]}: ${values.get("name") || ""}`,
    `${t.form[1]}: ${values.get("company") || ""}`,
    `${t.form[2]}: ${values.get("email") || ""}`,
    `${t.form[3]}: ${values.get("interest") || ""}`,
    "",
    values.get("message") || ""
  ].join("\n"));

  const button = form.querySelector(".contactSubmit");
  const buttonLabel = button.querySelector("span:first-child");
  const status = form.querySelector(".formStatus");
  button.disabled = true;
  button.classList.add("is-loading");
  button.setAttribute("aria-busy", "true");
  buttonLabel.textContent = t.formProcessing;
  status.textContent = t.formProcessing;

  window.setTimeout(() => {
    window.location.href = `mailto:business@neosyrpharm.com?subject=${subject}&body=${body}`;
  }, 180);

  window.setTimeout(() => {
    const activeTranslations = content[currentLanguage];
    button.disabled = false;
    button.classList.remove("is-loading");
    button.removeAttribute("aria-busy");
    buttonLabel.textContent = activeTranslations.form[5];
    status.textContent = "";
  }, 1400);
});

